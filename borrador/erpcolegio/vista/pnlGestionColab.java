    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        boolean exito = controlador.guardarColaborador(
            txtDni.getText(), txtNombres.getText(), txtApellidos.getText(), dcFechaNac.getDate(),
            txtTelefono.getText(), txtCorreo.getText(), cbCargo.getSelectedIndex(), cbRegimen.getSelectedIndex(),
            cbCondicion.getSelectedItem().toString(), dcInicioContrato.getDate(),
            chkGenerarUsuario.isSelected(), txtUsername.getText(), new String(txtPassword.getPassword()), 
            cbRol.getSelectedIndex(), listaCargos, listaRegimenes, listaRoles
        );

        if(exito) {
            javax.swing.JOptionPane.showMessageDialog(this, "Colaborador registrado correctamente.");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: Revise los datos, formato de DNI, o el usuario/DNI ya existe.");
        }
        
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnCeseActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCeseActionPerformed
        // se necesita un buscador del id del colaborador teniendo solo el dni
        
        int idColaboradorSeleccionado = 1; // REEMPLAZAR con el ID real cargado en el panel

        // Solicitamos contraseña del usuario en sesión
        javax.swing.JPasswordField pwd = new javax.swing.JPasswordField(10);
        int action = javax.swing.JOptionPane.showConfirmDialog(this, pwd, "Ingrese su contraseña para autorizar el Cese", javax.swing.JOptionPane.OK_CANCEL_OPTION);

        if (action == javax.swing.JOptionPane.OK_OPTION) {
            String inputPass = new String(pwd.getPassword());
            com.erpcolegio.controlador.LoginController login = new com.erpcolegio.controlador.LoginController();

            //  Re-validamos contra la bd usando el controller de Login
            if (login.procesarLogin(com.erpcolegio.util.SesionGlobal.usuarioActual.getUsername(), inputPass)) {

                com.erpcolegio.dao.ColaboradorDAO dao = new com.erpcolegio.dao.ColaboradorDAO();
                if(dao.cesarColaborador(idColaboradorSeleccionado)){
                    javax.swing.JOptionPane.showMessageDialog(this, "Cese lógico registrado. Contrato finalizado y usuario bloqueado.");
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Error en la base de datos.");
                }
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Autorización denegada: Contraseña incorrecta.");
            }
        }
    }//GEN-LAST:event_btnCeseActionPerformed


