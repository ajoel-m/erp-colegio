    private void cargarCatalogos() {
        listaCargos = controlador.obtenerCargos();
        cbCargo.removeAllItems();
        for(com.erpcolegio.modelo.CategoriaColaborador c : listaCargos) cbCargo.addItem(c.getPuestoColaborador());

        listaRegimenes = controlador.obtenerRegimenes();
        cbRegimen.removeAllItems();
        for(com.erpcolegio.modelo.RegimenLaboral r : listaRegimenes) cbRegimen.addItem(r.getNombreRegimen());

        listaRoles = controlador.obtenerRoles();
        cbRol.removeAllItems();
        for(com.erpcolegio.modelo.Rol r : listaRoles) cbRol.addItem(r.getNombreRol());
    }

    private void cargarCombosEstaticos() {
        cbCondicion.removeAllItems();
        cbCondicion.addItem("CONTRATADO");
        cbCondicion.addItem("NOMBRADO");
    }
