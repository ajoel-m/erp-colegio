    private void cargarCombosEstaticos() {
        cbNivel.removeAllItems();
        cbNivel.addItem("primaria");
        cbNivel.addItem("secundaria");

        cbTurno.removeAllItems();
        cbTurno.addItem("MAÑANA");
        cbTurno.addItem("TARDE");
    }  
    
    private void cargarDatosBase() {
        cbAnio.removeAllItems();
        for (com.erpcolegio.modelo.AnioLectivo anio : controlador.obtenerAnios()) {
            cbAnio.addItem(anio.getAnio()); 
        }

        cbSeccion.removeAllItems();
        for (com.erpcolegio.modelo.Seccion sec : controlador.obtenerSecciones()) {
            cbSeccion.addItem(sec.getNombreSeccion());
        }
    }
    
    private void cargarTabla() {
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tblAulas.getModel();
        modelo.setRowCount(0);

        for (com.erpcolegio.modelo.GradoSeccionAnio gsa : controlador.obtenerAulasConfiguradas()) {
            modelo.addRow(new Object[]{
                gsa.getAnioLectivoStr(),
                gsa.getNivelStr(),
                gsa.getGradoInt() + "° Grado",
                gsa.getSeccionStr(),
                gsa.getTurno(),
                gsa.getVacantes(),
                gsa.getVacantesOcupadas()
            });
        }
    }
    
    
