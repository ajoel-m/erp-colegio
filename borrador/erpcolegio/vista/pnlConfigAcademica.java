    private void cbNivelItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_cbNivelItemStateChanged
        // cambio dinamico de los grados
        if (evt.getStateChange() == java.awt.event.ItemEvent.SELECTED) {
            String nivelSel = cbNivel.getSelectedItem().toString();
            cbGrado.removeAllItems();
            for (com.erpcolegio.modelo.Grado g : controlador.obtenerGradosPorNivel(nivelSel)) {
                cbGrado.addItem(g.getGrado() + "° Grado");
            }
        }
    }//GEN-LAST:event_cbNivelItemStateChanged

    private void btnAgregarAulaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarAulaActionPerformed
        int indexAnio = cbAnio.getSelectedIndex();
        int indexGrado = cbGrado.getSelectedIndex();
        int indexSeccion = cbSeccion.getSelectedIndex();

        if(indexAnio == -1 || indexGrado == -1 || indexSeccion == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Debe seleccionar Año, Grado y Sección.");
            return;
        }

        com.erpcolegio.modelo.AnioLectivo anioObj = controlador.obtenerAnios().get(indexAnio);
        String nivel = cbNivel.getSelectedItem().toString();
        com.erpcolegio.modelo.Grado gradoObj = controlador.obtenerGradosPorNivel(nivel).get(indexGrado);
        com.erpcolegio.modelo.Seccion seccionObj = controlador.obtenerSecciones().get(indexSeccion);

        String turno = cbTurno.getSelectedItem().toString();
        String vacantes = txtVacantes.getText().trim();

        if (controlador.agregarAula(anioObj, gradoObj, seccionObj, turno, vacantes)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Aula registrada correctamente.");
            cargarTabla();
            txtVacantes.setText("");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Error de validación o el aula ya está configurada.");
        }
    }//GEN-LAST:event_btnAgregarAulaActionPerformed

    private void btnAperturarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAperturarActionPerformed
        String anio = txtAnio.getText().trim();
        java.util.Date inicio = dcInicio.getDate();
        java.util.Date fin = dcFin.getDate();

        if (controlador.aperturarAnio(anio, inicio, fin)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Año lectivo aperturado correctamente.");
            cargarDatosBase();
            txtAnio.setText("");
            dcInicio.setDate(null);
            dcFin.setDate(null);
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: Verifique las fechas, el formato del año o si ya existe.");
        }
    }//GEN-LAST:event_btnAperturarActionPerformed


